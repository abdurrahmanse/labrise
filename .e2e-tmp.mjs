import { chromium } from "playwright";
const b = await chromium.launch();
const p = await b.newPage();
const errors = [];
p.on("pageerror", (e) => errors.push(e.message));
const base = "http://localhost:3115";
await p.goto(base + "/contact");
await p.locator("form button[type=submit]").click();
console.log("contact invalid fields after empty submit:", await p.locator("input[aria-invalid='true'], textarea[aria-invalid='true']").count());
await p.fill("#contact-name", "Ada");
console.log("name error cleared on edit:", (await p.locator("#contact-name[aria-invalid='true']").count()) === 0);
await p.goto(base + "/");
await p.keyboard.press("Control+k");
await p.waitForSelector("dialog[open]");
await p.keyboard.type("daad");
await p.waitForSelector("[role=option]", { timeout: 8000 });
const n = await p.locator("[role=option]").count();
await p.keyboard.press("ArrowDown");
const sel = await p.locator("[role=option][aria-selected=true]").innerText();
console.log("search results:", n, "| selected after ArrowDown:", sel.split("\n")[0]);
await p.keyboard.press("Escape");
console.log("dialog closed:", (await p.locator("dialog[open]").count()) === 0);
await p.goto(base + "/faqs");
const counter = p.getByText(/of \d+ Questions/).first();
const before = await counter.innerText();
await p.locator("#faq-list input").first().fill("IELTS");
console.log("faq counter:", before, "->", await counter.innerText());
await p.goto(base + "/scholarships/browse");
const c1 = await p.locator("a[href^='/directory/scholarships/']").count();
await p.getByRole("button", { name: /load more/i }).click();
await p.waitForTimeout(1000);
console.log("browse cards:", c1, "->", await p.locator("a[href^='/directory/scholarships/']").count());
console.log("page errors:", errors.length ? errors : "none");
await b.close();
